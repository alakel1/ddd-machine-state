def normalize(lang: str | None) -> str:
    """'it-IT', 'it', 'IT' -> 'it'; lingue non supportate -> lingua di default."""
    code = (lang or "").split(",")[0].split("-")[0].strip().lower()
    return code if code in MESSAGES else DEFAULT_LANG


def translator(lang: str | None = None):
    msgs = MESSAGES[normalize(lang)]

    def t(key: str, **params) -> str:
        return msgs[key].format(**params) if params else msgs[key]

    t.lang = normalize(lang)
    return t
